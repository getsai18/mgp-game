// Une casillas sólidas en rectángulos grandes (menos cuerpos físicos):
// tramos horizontales por fila y luego se extienden hacia abajo si la fila siguiente es idéntica.
function mergeSolids(rows) {
  const isSolid = (r, c) => SOLID.includes(rows[r][c]);
  const used = rows.map((r) => [...r].map(() => false));
  const rects = [];
  for (let r = 0; r < rows.length; r++) {
    for (let c = 0; c < rows[r].length; c++) {
      if (!isSolid(r, c) || used[r][c]) continue;
      let c2 = c;
      while (c2 + 1 < rows[r].length && isSolid(r, c2 + 1) && !used[r][c2 + 1]) c2++;
      let r2 = r;
      const rowMatches = (rr) => {
        for (let k = c; k <= c2; k++) if (!isSolid(rr, k) || used[rr][k]) return false;
        return true;
      };
      while (r2 + 1 < rows.length && rowMatches(r2 + 1)) r2++;
      for (let rr = r; rr <= r2; rr++) for (let k = c; k <= c2; k++) used[rr][k] = true;
      rects.push({ x: c * TILE, y: r * TILE, w: (c2 - c + 1) * TILE, h: (r2 - r + 1) * TILE });
    }
  }
  return rects;
}

// Tramos horizontales de un carácter (plataformas finas, pinchos).
function runsOf(rows, ch) {
  const runs = [];
  rows.forEach((row, r) => {
    for (let c = 0; c < row.length; c++) {
      if (row[c] !== ch) continue;
      let c2 = c;
      while (row[c2 + 1] === ch) c2++;
      runs.push({ x: c * TILE, y: r * TILE, w: (c2 - c + 1) * TILE });
      c = c2;
    }
  });
  return runs;
}

function parse({ name, theme, rows }) {
  const spawns = [];
  const weaponSpawns = [];
  const decor = [];
  rows.forEach((row, r) => {
    for (let c = 0; c < row.length; c++) {
      const ch = row[c];
      if (ch === 'A' || ch === 'B') {
        // Pies apoyados en la casilla de abajo (el cuerpo del jugador mide 40 px, origen al centro).
        spawns[ch === 'A' ? 0 : 1] = { x: c * TILE + TILE / 2, y: (r + 1) * TILE - 20 };
      } else if (ch === 'w' || ch === 'c') {
        weaponSpawns.push({ x: c * TILE + TILE / 2, y: (r + 1) * TILE - 8 });
      } else if (DECOR.includes(ch)) {
        decor.push({ type: ch, r, c });
      }
    }
  });
  return {
    name,
    theme,
    rows,
    deathY: theme.deathY,
    solids: mergeSolids(rows),
    oneWays: runsOf(rows, '-'),
    // Pinchos: solo la mitad inferior de la casilla mata.
    spikes: runsOf(rows, '^').map((s) => ({ ...s, y: s.y + TILE / 2, h: TILE / 2 })),
    spawns,
    weaponSpawns,
    decor,
  };
}

export const MAPS = RAW.map(parse);

export const mapForRound = (round) => (round - 1) % MAPS.length;
